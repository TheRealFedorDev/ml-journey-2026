'''

1. id — идентификатор пациента
Тип: Уникальный номер

Значения: 0, 1, 2, ..., 69999

Примечание: Удаляем, не несёт информации для модели

2. age — возраст
Тип: Числовой (целое)

Значения: В днях! Например: 18393 дней ≈ 50.4 лет

Диапазон: ~ 30-65 лет (в днях: 10950-23725)

Медицинский смысл: Главный фактор риска сердечных заболеваний

3. gender — пол
Тип: Категориальный (кодирован числом)

Значения:

1 = женщины

2 = мужчины

Медицинский смысл: Мужчины имеют более высокий риск в молодом возрасте

4. height — рост
Тип: Числовой (целое)

Значения: В сантиметрах

Диапазон: 140-210 см (реальные значения после очистки)

Пример: 168 см, 175 см, 182 см

5. weight — вес
Тип: Числовой (дробное)

Значения: В килограммах

Диапазон: 40-180 кг (после очистки)

Пример: 62.0 кг, 85.0 кг, 72.5 кг

6. ap_hi — систолическое артериальное давление
Тип: Числовой (целое)

Значения: В мм рт. ст.

Норма: 90-140 мм рт. ст.

Гипертония: ≥140 мм рт. ст.

Диапазон после очистки: 90-250 мм рт. ст.

7. ap_lo — диастолическое артериальное давление
Тип: Числовой (целое)

Значения: В мм рт. ст.

Норма: 60-90 мм рт. ст.

Гипертония: ≥90 мм рт. ст.

Диапазон после очистки: 60-150 мм рт. ст.

8. cholesterol — уровень холестерина
Тип: Категориальный (кодирован числом)

Значения:

1 = нормальный (Normal)

2 = выше нормального (Above normal)

3 = сильно повышен (Well above normal)

Медицинский смысл: Высокий холестерин → риск атеросклероза

9. gluc — уровень глюкозы
Тип: Категориальный (кодирован числом)

Значения:

1 = нормальный (Normal)

2 = выше нормального (Above normal)

3 = сильно повышен (Well above normal)

Медицинский смысл: Предиабет/диабет → риск сердечных заболеваний

10. smoke — курение
Тип: Бинарный

Значения:

0 = не курит

1 = курит

Медицинский смысл: Курение повреждает сосуды

11. alco — употребление алкоголя
Тип: Бинарный

Значения:

0 = не употребляет

1 = употребляет

Медицинский смысл: Избыток алкоголя вредит сердцу

12. active — физическая активность
Тип: Бинарный

Значения:

0 = не активен

1 = активен

Медицинский смысл: Активность защищает сердце

13. cardio — наличие сердечно-сосудистых заболеваний (ЦЕЛЕВАЯ ПЕРЕМЕННАЯ)
Тип: Бинарный

Значения:

0 = нет заболеваний

1 = есть заболевания

Распределение: Примерно 50%/50% (сбалансировано)





'''

# predictor.py
import joblib
import pandas as pd

# Загружаем модель и препроцессор
model = joblib.load('best_cardio_model.pkl')
preprocessor = joblib.load('cardio_preprocessor.pkl')


def predict_heart_disease(patient_data):
    """
    Предсказывает риск сердечного заболевания

    patient_data: dict с ключами:
    - age: возраст в днях
    - gender: 1 (жен), 2 (муж)
    - height: рост в см
    - weight: вес в кг
    - ap_hi: систолическое давление
    - ap_lo: диастолическое давление
    - cholesterol: 1 (норма), 2 (выше нормы), 3 (высокий)
    - gluc: 1 (норма), 2 (выше нормы), 3 (высокий)
    - smoke: 0 (нет), 1 (да)
    - alco: 0 (нет), 1 (да)
    - active: 0 (нет), 1 (да)
    """
    # Создаём DataFrame
    df = pd.DataFrame([patient_data])

    # Добавляем вычисляемые признаки
    df['age_years'] = df['age'] // 365
    df['bmi'] = df['weight'] / ((df['height'] / 100) ** 2)

    # Преобразуем
    X = preprocessor.transform(df)

    # Предсказываем
    probability = model.predict_proba(X)[0][1]

    # Интерпретация
    if probability < 0.4:
        risk = "низкий"
    elif probability < 0.6:
        risk = "умеренный"
    elif probability < 0.8:
        risk = "высокий"
    else:
        risk = "очень высокий"

    return {
        'probability': probability,
        'risk_level': risk,
        'recommendation': f"Рекомендуется консультация кардиолога" if probability > 0.5 else "Профилактический осмотр"
    }


# Пример использования
patient = {
    'age': 18000,  # ~49 лет
    'gender': 2,
    'height': 175,
    'weight': 85,
    'ap_hi': 145,
    'ap_lo': 95,
    'cholesterol': 3,
    'gluc': 1,
    'smoke': 1,
    'alco': 0,
    'active': 0
}

result = predict_heart_disease(patient)
print(f"Вероятность заболевания: {result['probability']:.1%}")
print(f"Уровень риска: {result['risk_level']}")
print(f"Рекомендация: {result['recommendation']}")