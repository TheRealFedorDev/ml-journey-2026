import torch

# ========== ЧАСТЬ 1: Тензоры ==========
print("=== Часть 1: Тензоры ===")

# Создайте тензор размерности (2, 3) со случайными значениями
x = torch.randn(2, 3)
print(f"x = \n{x}")
print(f"Форма x: {x.shape}")
print(f"Тип x: {x.dtype}")

# Создайте тензор из списка
y = torch.tensor([[1, 2, 3], [4, 5, 6]])
print(f"\ny = \n{y}")

# Операции с тензорами
z = x + y  # поэлементное сложение
print(f"\nz = x + y = \n{z}")

# Матричное умножение (важно!)
# Для этого x должно быть размерности (2, 3), а y - (3, 2)
y_t = y.T  # транспонирование
print(f"\ny транспонированное = \n{y_t}")

# Изменим форму x для матричного умножения
x_reshaped = x.reshape(3, 2)  # теперь x имеет форму (3, 2)
print(f"\nx измененной формы = \n{x_reshaped}")

# Матричное умножение
matmul_result = torch.matmul(x_reshaped, y_t)
print(f"\nМатричное умножение x @ y^T = \n{matmul_result}")

# ========== ЧАСТЬ 2: Автоград ==========
print("\n\n=== Часть 2: Автоматическое дифференцирование ===")

# Создаем тензор с require_grad=True
w = torch.tensor([2.0], requires_grad=True)
b = torch.tensor([1.0], requires_grad=True)

# Простая функция: f(x) = w*x^2 + b
x_input = torch.tensor([3.0])

# Вычисляем функцию
y_pred = w * x_input**2 + b
print(f"y_pred = {y_pred.item()}")

# Вычисляем градиенты
y_pred.backward()

# Градиенты сохраняются в .grad
print(f"Градиент по w: {w.grad.item()}")
print(f"Градиент по b: {b.grad.item()}")

# Проверка: аналитический расчет
# dy/dw = x^2 = 9
# dy/db = 1
print(f"Ожидаемый градиент по w: {x_input.item()**2}")
print(f"Ожидаемый градиент по b: 1.0")

